#!/usr/bin/env node
// Seed PvP bot characters + saves into the D1 database.
//
// Usage (local D1 dev database):
//   npx wrangler d1 execute pocketrpg --local --command "$(node scripts/seed-pvp-bots.cjs)"
//
// Or pipe directly:
//   node scripts/seed-pvp-bots.cjs | npx wrangler d1 execute pocketrpg --local --file=-
//
// The script is idempotent — re-running updates existing bot rows rather
// than inserting duplicates (keyed on username via the UNIQUE constraint).
//
// Requirements: must be run from the repository root.

'use strict'

const path = require('path')
const zlib = require('zlib')

const root = path.resolve(__dirname, '..')
const pvpBots = require(path.join(root, 'src/data/pvpBots.json'))

// XP table (mirrors src/engine/experience.js) --------------------------------
const MAX_LEVEL = 99
const XP_TABLE = new Array(MAX_LEVEL + 1)
XP_TABLE[1] = 0
;(function buildXPTable() {
  let cumulative = 0
  for (let level = 1; level < MAX_LEVEL; level++) {
    cumulative += Math.floor(level + 300 * Math.pow(2, level / 7))
    XP_TABLE[level + 1] = Math.floor(cumulative / 4)
  }
})()

function getXPForLevel(level) {
  if (level < 1) return 0
  if (level > MAX_LEVEL) return XP_TABLE[MAX_LEVEL]
  return XP_TABLE[Math.floor(level)]
}

// Combat level formula (mirrors functions/_lib/combatLevel.js) ----------------
function getLevelFromXP(xp) {
  if (xp <= 0) return 1
  for (let l = MAX_LEVEL; l >= 2; l--) {
    if (XP_TABLE[l] <= xp) return l
  }
  return 1
}

function getCombatLevel(stats) {
  const lvl = (skill) => getLevelFromXP(stats[skill] || 0)
  const atk  = lvl('attack')
  const str  = lvl('strength')
  const def  = lvl('defence')
  const hp   = lvl('hitpoints')
  const pray = lvl('prayer')
  const rng  = lvl('ranged')
  const mage = lvl('magic')
  const base  = 0.25 * (def + hp + Math.floor(pray / 2))
  const melee = 0.325 * (atk + str)
  const range = 0.325 * (Math.floor(rng / 2) + rng)
  const magic = 0.325 * (Math.floor(mage / 2) + mage)
  return Math.max(3, Math.floor(base + Math.max(melee, range, magic)))
}

// Build a save payload from a bot template ------------------------------------
function buildSavePayload(template) {
  // Convert level → XP for each stat
  const stats = {}
  for (const [skill, level] of Object.entries(template.stats)) {
    stats[skill] = { xp: getXPForLevel(level) }
  }

  // Derive maxHP from hitpoints level
  const hpLevel = template.stats.hitpoints || 10
  const maxHP   = Math.max(10, hpLevel)

  return {
    stats,
    equipment: template.equipment || {},
    inventory: (template.inventory || []).map((slot) => slot || null),
    settings: { combatStance: template.combatStance || 'accurate' },
    player: { currentHP: maxHP },
    bank: {},
  }
}

// Gzip a JSON string synchronously (Node.js zlib) -----------------------------
function gzipSync(jsonString) {
  const buf = zlib.gzipSync(Buffer.from(jsonString, 'utf8'))
  // Emit as hex literal so it round-trips through the SQL text safely
  return buf.toString('hex')
}

// Emit SQL statements ---------------------------------------------------------
const SYSTEM_PROVIDER    = 'system'
const SYSTEM_PROVIDER_ID = 'pvp-bots'
const SYSTEM_EMAIL       = null
const SYSTEM_DISPLAY     = 'PocketRPG Bots'

const lines = [
  '-- Auto-generated by scripts/seed-pvp-bots.cjs — do not hand-edit.',
  '-- Run: node scripts/seed-pvp-bots.cjs | npx wrangler d1 execute pocketrpg --local --file=-',
  '',
  '-- 1. System identity that owns all bots',
  `INSERT INTO oauth_identities (provider, provider_user_id, email, display_name, created_at)`,
  `  VALUES ('${SYSTEM_PROVIDER}', '${SYSTEM_PROVIDER_ID}', ${SYSTEM_EMAIL ? `'${SYSTEM_EMAIL}'` : 'NULL'}, '${SYSTEM_DISPLAY}', ${Date.now()})`,
  `  ON CONFLICT(provider, provider_user_id) DO NOTHING;`,
  '',
]

for (const template of pvpBots.bots) {
  const savePayload = buildSavePayload(template)
  const xpStats = {}
  for (const [skill, level] of Object.entries(template.stats)) {
    xpStats[skill] = getXPForLevel(level)
  }
  const combatLevel = getCombatLevel(xpStats)
  const now = Date.now()
  const saveJson = JSON.stringify(savePayload)
  const saveHex  = gzipSync(saveJson)

  // Total level = sum of all skill levels
  const totalLevel = Object.values(template.stats).reduce((s, l) => s + l, 0)

  lines.push(`-- Bot: ${template.id} (${template.username})`)
  lines.push(`INSERT INTO characters`)
  lines.push(`  (owner_id, username, created_at, is_bot, bot_template_id, combat_level, total_level)`)
  lines.push(`  SELECT oi.id, '${template.username}', ${now}, 1, '${template.id}', ${combatLevel}, ${totalLevel}`)
  lines.push(`    FROM oauth_identities oi`)
  lines.push(`   WHERE oi.provider = '${SYSTEM_PROVIDER}' AND oi.provider_user_id = '${SYSTEM_PROVIDER_ID}'`)
  lines.push(`  ON CONFLICT(username) DO UPDATE SET`)
  lines.push(`    bot_template_id = excluded.bot_template_id,`)
  lines.push(`    combat_level    = excluded.combat_level,`)
  lines.push(`    total_level     = excluded.total_level;`)
  lines.push('')
  lines.push(`INSERT INTO saves (character_id, base64, save_blob, hash, updated_at)`)
  lines.push(`  SELECT c.id, '', X'${saveHex}', 'seed', ${now}`)
  lines.push(`    FROM characters c WHERE c.username = '${template.username}' AND c.is_bot = 1`)
  lines.push(`  ON CONFLICT(character_id) DO UPDATE SET`)
  lines.push(`    save_blob  = excluded.save_blob,`)
  lines.push(`    updated_at = excluded.updated_at;`)
  lines.push('')
}

console.log(lines.join('\n'))
