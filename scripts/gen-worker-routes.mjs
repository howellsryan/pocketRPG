#!/usr/bin/env node
// Regenerates worker/routes.js from the functions/ tree.
//
// The table has to be static imports (a Worker cannot glob at runtime), so it
// is generated rather than hand-listed: a route added to functions/ and
// forgotten here is a 404 in production that no type-checker would catch.
// tests/workerRoutes.test.ts re-derives the same list and fails on drift, so
// forgetting to run this is a red build rather than a missing endpoint.
import { readdirSync, statSync, writeFileSync } from 'node:fs'
import { join, relative, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')

/** Every routable file under functions/, as paths relative to functions/.
 * Leading-underscore names are Pages' convention for non-routes (_lib,
 * _middleware, _completeShared) and are skipped exactly as Pages skipped them. */
export function routeFiles(functionsDir) {
  const out = []
  const walk = (dir) => {
    for (const entry of readdirSync(dir).sort()) {
      if (entry.startsWith('_')) continue
      const full = join(dir, entry)
      if (statSync(full).isDirectory()) { walk(full); continue }
      if (!entry.endsWith('.js')) continue
      out.push(relative(functionsDir, full).split('\\').join('/'))
    }
  }
  walk(functionsDir)
  return out
}

/** A stable, collision-free JS identifier for a route module import. */
export function moduleIdentifier(relativePath) {
  const base = relativePath
    .replace(/\.js$/, '')
    .replace(/\[\[(.+?)\]\]/g, 'all_$1')
    .replace(/\[(.+?)\]/g, 'p_$1')
    .replace(/[^A-Za-z0-9]+/g, ' ')
    .trim()
    .split(' ')
    .map((word, i) => (i === 0 ? word : word[0].toUpperCase() + word.slice(1)))
    .join('')
  return 'route_' + base
}

function generate(functionsDir) {
  const files = routeFiles(functionsDir)
  const imports = files
    .map((f) => `import * as ${moduleIdentifier(f)} from '../functions/${f}'`)
    .join('\n')
  const entries = files
    .map((f) => `  { file: ${JSON.stringify(f)}, module: ${moduleIdentifier(f)} },`)
    .join('\n')
  return `// GENERATED by scripts/gen-worker-routes.mjs — do not edit by hand.
// Run \`npm run gen:routes\` after adding or removing a file under functions/.
${imports}

/** Every routable handler module, keyed by its path relative to functions/.
 * routePathForFile() in router.js turns each into the URL it answers. */
export const ROUTE_MODULES = [
${entries}
]
`
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const functionsDir = join(root, 'functions')
  writeFileSync(join(root, 'worker', 'routes.js'), generate(functionsDir))
  console.log(`worker/routes.js: ${routeFiles(functionsDir).length} routes`)
}
