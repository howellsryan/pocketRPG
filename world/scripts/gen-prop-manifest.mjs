#!/usr/bin/env node
// Regenerates client/src/editor/propManifest.ts from the GLBs in
// client/public/models/props/. Drop a prop model in that folder and it appears
// in the editor library after the next build — no hand-editing. Runs before
// every build (see package.json). Keeps public/ assets un-bundled (the editor
// only needs the names; the files are served straight from public/).
import { readdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const worldDir = fileURLToPath(new URL('..', import.meta.url))
const propsDir = path.join(worldDir, 'client', 'public', 'models', 'props')
const outFile = path.join(worldDir, 'client', 'src', 'editor', 'propManifest.ts')

let names = []
try {
  names = readdirSync(propsDir)
    .filter((f) => f.endsWith('.glb'))
    .map((f) => f.replace(/\.glb$/, ''))
    .sort()
} catch {
  names = []
}

const body = `// GENERATED by scripts/gen-prop-manifest.mjs — do not edit by hand.
// Prop model basenames discovered in client/public/models/props/.
export const PROP_MODELS: string[] = ${JSON.stringify(names, null, 2)}
`
writeFileSync(outFile, body)
console.log(`gen-prop-manifest: ${names.length} props → ${path.relative(worldDir, outFile)}`)
